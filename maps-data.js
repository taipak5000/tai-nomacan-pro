// ソルとシュガ様(@sky_solsuga)公開のエリア地図で示されている実際の位置関係
// （スタート地点・エリア間の接続・上下関係）を参考に、描画自体は完全オリジナルの
// 手描き風模式図として描き起こしたものです（画像素材の転載・トレースはしていません）。
// regions のキーは areas-data.js のサブエリア名、spots のキーはスポット名と
// 一致させることで、実行時に名前でマッチングして地図上へ配置します。
// 座標はその地図の viewBox（w×h）内の絶対座標です。

(function () {
    // 文字列 → 決定的な32bit seed
    const hashStr = (str) => {
        let h = 0;
        for (let i = 0; i < str.length; i++) h = (Math.imul(h, 31) + str.charCodeAt(i)) >>> 0;
        return h;
    };

    // seed付き乱数（mulberry32）
    const seededRand = (seed) => {
        let t = seed >>> 0;
        return () => {
            t += 0x6D2B79F5;
            let x = Math.imul(t ^ (t >>> 15), 1 | t);
            x ^= x + Math.imul(x ^ (x >>> 7), 61 | x);
            return ((x ^ (x >>> 14)) >>> 0) / 4294967296;
        };
    };

    // 中心(cx,cy)・半径(rx,ry)・seed から、手描き風の有機的な閉曲線（地形ブロブ）を生成
    const blobPath = (cx, cy, rx, ry, seed, points = 9, irregularity = 0.16) => {
        const rand = seededRand(seed);
        const pts = [];
        for (let i = 0; i < points; i++) {
            const ang = (Math.PI * 2 * i) / points;
            const jit = 1 - irregularity + rand() * irregularity * 2;
            pts.push([cx + Math.cos(ang) * rx * jit, cy + Math.sin(ang) * ry * jit]);
        }
        let d = `M ${pts[0][0].toFixed(1)} ${pts[0][1].toFixed(1)}`;
        for (let i = 0; i < points; i++) {
            const p0 = pts[(i - 1 + points) % points], p1 = pts[i],
                  p2 = pts[(i + 1) % points], p3 = pts[(i + 2) % points];
            const c1 = [p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6];
            const c2 = [p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6];
            d += ` C ${c1[0].toFixed(1)} ${c1[1].toFixed(1)}, ${c2[0].toFixed(1)} ${c2[1].toFixed(1)}, ${p2[0].toFixed(1)} ${p2[1].toFixed(1)}`;
        }
        return d + ' Z';
    };

    window.SkyMapGeo = { hashStr, blobPath };
})();

